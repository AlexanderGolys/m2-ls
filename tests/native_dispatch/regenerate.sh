#!/bin/bash
# Rebuilds dead_pairs.txt from the installed Macaulay2: the operand classes for
# which an installed operator method is never called (see probe.m2).
set -f
cd "$(dirname "$0")"
M2=${M2:-M2}
binary=('<<' '>>' '==' '?' '||' '<==>' '|-' '??' '==>' '===>' '<==' '<===' ':' '^^' '&' '..' '..<'
    '-' '+' '++' '**' '*' '\\' '/' '\' '%' '//' '@' '@@' '@@?' 'or' 'and' 'xor' '~' '|_' '^' '_'
    '^>' '_>' '^>=' '_>=' '^<' '_<' '^<=' '_<=' '^**' '·' '⊠' '⧢')
prefix=('-' '+' '~' 'not' '?' '<<' '??' '|-' '<==' '<===')
postfix=('!' '^!' '_!' '^*' '_*' '^~' '_~')
{
    echo "# Generated by regenerate.sh with $($M2 --version) -- do not edit."
    echo "# Operand classes for which an installed operator method is never called."
    echo "# Probed classes: $($M2 --script probe.m2 classes </dev/null)"
    echo "# Probed binary operators: ${binary[*]}"
    echo "# Probed prefix operators: ${prefix[*]}"
    echo "# Probed postfix operators: ${postfix[*]}"
    for operator in "${binary[@]}"; do $M2 --script probe.m2 bin "$operator" </dev/null; done
    for operator in "${prefix[@]}"; do $M2 --script probe.m2 pre "$operator" </dev/null; done
    for operator in "${postfix[@]}"; do $M2 --script probe.m2 post "$operator" </dev/null; done
} > dead_pairs.txt
